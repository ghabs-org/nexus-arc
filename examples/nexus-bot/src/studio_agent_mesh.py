"""Nexus Bot example consumer for native Agent Mesh architecture.

Demonstrates decoupled event-driven choreography, dynamic capability routing,
and request-reply correlation without external broker dependencies.
"""

import asyncio
from nexus.core.agent_mesh import (
    AgentMesh,
    AgentMeshEnvelope,
    AgentMeshTopic,
    RoutingStrategy,
)


async def main() -> None:
    print("--- Initializing Native Nexus Agent Mesh ---")
    mesh = AgentMesh()

    # 1. Register agents with capabilities/skills
    mesh.register_peer("analyzer-1", "Data analyzer", skills=["data_analysis", "sql"])
    mesh.register_peer("analyzer-2", "Data analyzer 2", skills=["data_analysis", "python"])
    mesh.register_peer("reporter", "Report generator", skills=["reporting", "markdown"])

    print(f"Active peers registered: {[p.name for p in mesh.get_active_peers()]}")

    # 2. Set up responder worker for reporting
    async def reporting_worker(env: AgentMeshEnvelope) -> None:
        title = env.payload.get("title", "Untitled")
        content = f"# {title}\nGenerated by {env.recipient} via Agent Mesh"
        print(f"[{env.recipient}] Received request, generating report...")
        await mesh.reply(env, payload={"status": "completed", "report": content})

    mesh.subscribe(AgentMeshTopic.agent_inbox("reporter"), reporting_worker)

    # 3. Dynamic capability routing across analyzer pool
    received_tasks = []
    mesh.subscribe(
        "agents.analyzer-*.inbox",
        lambda env: received_tasks.append((env.recipient, env.payload)),
    )

    chosen_peer1, _ = await mesh.route_capability(
        skill="data_analysis",
        payload={"query": "SELECT COUNT(*) FROM telemetry"},
        strategy=RoutingStrategy.ROUND_ROBIN,
    )
    chosen_peer2, _ = await mesh.route_capability(
        skill="data_analysis",
        payload={"query": "SELECT AVG(latency) FROM telemetry"},
        strategy=RoutingStrategy.ROUND_ROBIN,
    )
    print(f"Dynamically routed capability tasks: {chosen_peer1}, {chosen_peer2}")
    assert len(received_tasks) == 2

    # 4. Request-Reply pattern with correlation ID
    print("Sending request to reporter...")
    reply = await mesh.request(
        target_topic=AgentMeshTopic.agent_inbox("reporter"),
        payload={"title": "Q3 Telemetry Summary"},
        sender="coordinator",
        timeout=5.0,
    )
    print(f"Received correlated reply from {reply.sender}:")
    print(reply.payload.get("report"))

    # 5. Broadcast lifecycle event
    notified = await mesh.broadcast("operations", {"status": "all_systems_go"})
    print(f"Broadcast sent to {notified} active topic subscribers")

    mesh.close()
    print("--- Agent Mesh demonstration completed cleanly ---")


if __name__ == "__main__":
    asyncio.run(main())
